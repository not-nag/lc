import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const dir = "storyboards";
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

const body = `// AUTO-GENERATED by scripts/index-storyboards.mjs — do not edit.
import { Storyboard as SB, type Storyboard } from "@/schema";
${files.map((f, i) => `import raw${i} from "../../storyboards/${f}";`).join("\n")}

const RAW: unknown[] = [${files.map((_, i) => `raw${i}`).join(", ")}];
const NAMES = [${files.map((f) => JSON.stringify(f)).join(", ")}];

function loadAll(): Storyboard[] {
  const out: Storyboard[] = [];
  RAW.forEach((r, i) => {
    const p = SB.safeParse(r);
    if (p.success) out.push(p.data);
    else console.error(\`[storyboards] \${NAMES[i]} failed schema:\`, p.error.issues.slice(0, 5));
  });
  return out.sort((a, b) => (a.meta.number ?? 0) - (b.meta.number ?? 0));
}

export const ALL_STORYBOARDS: Storyboard[] = loadAll();
export const STORYBOARD_FILES = NAMES;
`;
writeFileSync("src/lib/storyboards.ts", body);
console.log(`indexed ${files.length} storyboard(s): ${files.join(", ") || "(none)"}`);
